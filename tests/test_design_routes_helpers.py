"""
OmniSight — Design Studio Helper Unit Tests
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

Verifies markdown code-fence stripping and structured response handling
for CSS outputs generated by the Design Studio endpoints.
"""

from backend.api.design_routes import _strip_fences


def test_strip_fences_removes_css_markdown_wrappers():
    raw = "```css\n.hero-card { border-radius: 16px; }\n```"
    assert _strip_fences(raw) == ".hero-card { border-radius: 16px; }"


def test_strip_fences_handles_plain_css_unchanged():
    raw = "  .nav-bar { backdrop-filter: blur(8px); }  "
    assert _strip_fences(raw) == ".nav-bar { backdrop-filter: blur(8px); }"


def test_strip_fences_handles_structured_chunk_list():
    chunks = [{"text": "```\n"}, ".btn-glow { color: #fff; }", {"text": "\n```"}]
    assert _strip_fences(chunks) == ".btn-glow { color: #fff; }"
